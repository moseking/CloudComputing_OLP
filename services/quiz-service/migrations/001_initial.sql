CREATE TABLE quizzes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    course_id INTEGER NOT NULL CHECK (course_id>0),
    lesson_id INTEGER CHECK (lesson_id>0), title VARCHAR(150) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE questions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    quiz_id INTEGER NOT NULL REFERENCES quizzes(id),
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('single_choice','fill_blank')),
    prompt TEXT NOT NULL, correct_answer TEXT NOT NULL,
    points INTEGER NOT NULL DEFAULT 1 CHECK(points BETWEEN 1 AND 10), position INTEGER NOT NULL,
    UNIQUE(quiz_id,position)
);
CREATE TABLE answer_options (
    question_id INTEGER NOT NULL REFERENCES questions(id),
    option_id VARCHAR(30) NOT NULL, text TEXT NOT NULL, PRIMARY KEY(question_id,option_id)
);
CREATE TABLE quiz_attempts (
    id UUID PRIMARY KEY, user_id UUID NOT NULL, quiz_id INTEGER NOT NULL REFERENCES quizzes(id),
    score INTEGER NOT NULL, max_score INTEGER NOT NULL, correct_count INTEGER NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE quiz_answers (
    attempt_id UUID NOT NULL REFERENCES quiz_attempts(id), question_id INTEGER NOT NULL REFERENCES questions(id),
    submitted_answer TEXT NOT NULL, correct_answer TEXT NOT NULL, is_correct BOOLEAN NOT NULL,
    awarded_points INTEGER NOT NULL, PRIMARY KEY(attempt_id,question_id)
);
CREATE INDEX quiz_attempts_user_idx ON quiz_attempts(user_id,submitted_at DESC);
