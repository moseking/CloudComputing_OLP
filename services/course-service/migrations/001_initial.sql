CREATE TABLE languages (
    code VARCHAR(12) PRIMARY KEY, name VARCHAR(100) NOT NULL
);
CREATE TABLE courses (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    language_code VARCHAR(12) NOT NULL REFERENCES languages(code),
    level VARCHAR(2) NOT NULL CHECK (level IN ('A1','A2','B1','B2','C1')),
    title VARCHAR(150) NOT NULL, description TEXT NOT NULL,
    price BIGINT NOT NULL CHECK (price BETWEEN 0 AND 1000000000),
    currency VARCHAR(3) NOT NULL DEFAULT 'VND' CHECK (currency='VND'),
    prerequisites TEXT NOT NULL DEFAULT '', learning_goals TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE lessons (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    course_id INTEGER NOT NULL REFERENCES courses(id),
    title VARCHAR(150) NOT NULL, position INTEGER NOT NULL CHECK (position>0),
    theory TEXT NOT NULL, vocabulary JSONB NOT NULL DEFAULT '[]',
    grammar JSONB NOT NULL DEFAULT '[]', practice JSONB NOT NULL DEFAULT '[]',
    quiz_id INTEGER CHECK (quiz_id>0), UNIQUE(course_id,position)
);
CREATE TABLE enrollments (
    id UUID PRIMARY KEY, user_id UUID NOT NULL, course_id INTEGER NOT NULL REFERENCES courses(id),
    source VARCHAR(10) NOT NULL CHECK (source IN ('free','payment')),
    payment_id UUID, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), UNIQUE(user_id,course_id)
);
CREATE TABLE lesson_progress (
    user_id UUID NOT NULL, lesson_id INTEGER NOT NULL REFERENCES lessons(id),
    completed_at TIMESTAMPTZ NOT NULL DEFAULT now(), PRIMARY KEY(user_id,lesson_id)
);
CREATE TABLE payment_receipts (
    payment_id UUID PRIMARY KEY, user_id UUID NOT NULL,
    course_id INTEGER NOT NULL REFERENCES courses(id), amount BIGINT NOT NULL CHECK (amount>0),
    currency VARCHAR(3) NOT NULL CHECK (currency='VND'), received_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX enrollments_user_idx ON enrollments(user_id);
